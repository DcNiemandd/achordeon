// Generates apps/app/src/app/shared/build-info.ts — the version About shows.
//
// Under `shared/` because that is the one in-app layer a feature may import
// (apps/app/eslint.config.mjs): `src/app/*.ts` is the shell, and the shell is
// wiring, not something Settings is allowed to reach into.
//
// The version is a DATE, not a semver: nothing here is released, so `0.0.0` in
// package.json would be a number that never moves and never means anything. What
// a bug report actually needs is "which deploy am I on", and every deploy is a
// merge to main — so the commit date of HEAD is the answer. In CI that is the
// merge commit the workflow checked out, i.e. the day the pull request landed;
// locally it is whatever you last committed.
//
// `%cs` is the committer date, short (YYYY-MM-DD), which is the same field GitHub
// shows against the merge. No git (a tarball, a fresh export) → the file still
// generates, with `null`, and the About block drops the row rather than printing
// a lie.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..'); // apps/app

/** One `git log -1` field of HEAD, or null outside a checkout. */
function head(format) {
  try {
    const value = execFileSync('git', ['log', '-1', `--format=${format}`], {
      cwd: projectRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return value === '' ? null : value;
  } catch {
    return null;
  }
}

const out = `// GENERATED by apps/app/tools/gen-build-info.mjs — do not edit by hand.
// Regenerate: node apps/app/tools/gen-build-info.mjs

/** Commit date of the build (YYYY-MM-DD), or null outside a git checkout. */
export const BUILD_DATE: string | null = ${JSON.stringify(head('%cs'))};

/** Short commit of the build, or null outside a git checkout. Never shown in the
 * UI — a date is what a person can say back to you — but a bug report carries it,
 * because two deploys can share a day and only this says which one. */
export const BUILD_COMMIT: string | null = ${JSON.stringify(head('%h'))};
`;

writeFileSync(resolve(projectRoot, 'src/app/shared/build-info.ts'), out);
